export function abbreviationsFor(lang: string): { titles: Set<string>; general: Set<string> } {
  const base = lang.slice(0, 2);
  return {
    titles: new Set([...(titles[base] ?? []), ...(titles.en ?? [])]),
    general: new Set([...(general[base] ?? general.en ?? [])]),
  };
}
